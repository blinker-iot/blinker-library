'use strict';

// Public synthetic material only. Exercise the production Service sealer;
// the vault stub is not a KMS test and never sees a real account/DeviceKey.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const protocol = require('../../../aily-blinker-services/packages/device-v2-protocol/src');
const { sealGatewayAccess } = require('../../../aily-blinker-services/services/gateway/src/device-v2/edge-gateway-access');
const fixed = (size, byte) => Buffer.alloc(size, byte);
const seal = (nonce, secret) => sealGatewayAccess({
  operationId: fixed(16, 0x11), environmentId: 'prod-cn', tenantId: 'tenant-edge',
  edgeHubLogicalDeviceId: 'edge-hub-1', edgeHubDeviceKey: fixed(32, 0x42), deviceKeyVersion: 7,
  childLogicalDeviceId: 'child-1', childDeviceInstanceId: fixed(16, 0x22), accessEpoch: 9,
  controllerId: fixed(16, 0x33), credentialVersion: 1, presenceKeyVersion: 1,
  expiresAtUnixSeconds: 2000000000, gatewaySecret: fixed(32, secret), presenceKey: fixed(16, 0x55),
  randomBytes: size => fixed(size, nonce),
  vault: { encryptGatewaySecret: () => ({ ciphertext: fixed(32, 0), nonce: fixed(12, 0),
    authTag: fixed(16, 0), keyId: 'fixture-only', aadVersion: 1 }) },
});
const first = seal(0x44, 0x43);
const rewrapped = seal(0x45, 0x43);
const conflict = seal(0x46, 0x47);
assert(first.accessMaterialDigest.equals(rewrapped.accessMaterialDigest));
assert(!first.accessMaterialDigest.equals(conflict.accessMaterialDigest));
assert(!first.exactEnvelope.equals(rewrapped.exactEnvelope));
const ack = Buffer.from(protocol.encodeGatewayAccessDeliveryAck({ version: 2,
  operationId: fixed(16, 0x11), accessMaterialDigest: first.accessMaterialDigest, storageRevision: 1 }));
const array = (name, value) => `static const uint8_t ${name}[] = {\n${
  [...value].map(byte => `0x${byte.toString(16).padStart(2, '0')}`)
    .reduce((rows, byte, index) => { if (index % 12 === 0) rows.push([]); rows.at(-1).push(byte); return rows; }, [])
    .map(row => `    ${row.join(', ')},`).join('\n')}\n};\n`;
const header = '// Generated by tests/golden/server_gateway_envelope_probe.cjs --header.\n'
  + '// Synthetic non-secret fixtures; never use these credentials in a product.\n'
  + '#pragma once\n#include <stdint.h>\nnamespace gateway_envelope_probe {\n'
  + array('firstEnvelope', first.exactEnvelope) + array('rewrappedEnvelope', rewrapped.exactEnvelope)
  + array('conflictingEnvelope', conflict.exactEnvelope) + array('expectedAck', ack)
  + '} // namespace gateway_envelope_probe\n';
if (process.argv[2] === '--header') process.stdout.write(header);
else {
  assert.equal(process.argv.length, 2, 'Use no arguments to verify, or --header to generate');
  const target = path.join(__dirname, '../internal/arduino/Esp32GatewayEnvelopeProbe/EnvelopeVectors.h');
  assert.equal(fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), header);
  console.log('Service AES-GCM envelope / ESP32 fixture consistency passed');
}
